                scroll_pos <= 11'd0;
            end else if (frame_start) begin
                if (scroll_pos >= scroll_span - STEP_R)
                    scroll_pos <= 11'd0;
                else
                    scroll_pos <= scroll_pos + STEP_R;
            end
            text_bounds_q <= in_text;
            if (in_text)
                glyph_row_q <= glyph_rom[glyph_address];
            else
                glyph_row_q <= 16'd0;
            glyph_col_q <= glyph_col;
        end
    end

